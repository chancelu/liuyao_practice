/** 八宫世爻推演：从本宫纯卦逐爻递变到目标卦的路径 */
export interface PalaceStep { name: string; seq: number; seqName: string; shiPos: number; flipPos: number | null; isTarget: boolean }
export function palaceWalk(palace: string, targetKey: string): PalaceStep[] {
  const data = PALACES[palace];
  const SHI = [0, 6, 1, 2, 3, 4, 5, 4, 3];
  const seqNames = ['', '本宫（纯卦）', '一世卦', '二世卦', '三世卦', '四世卦', '五世卦', '游魂卦', '归魂卦'];
  const flipMap: (number | null)[] = [null, null, 1, 2, 3, 4, 5, 4, null]; // 相对前一卦所变之爻
  return data.hexes.map((h) => ({
    name: h.name, seq: h.seq, seqName: seqNames[h.seq], shiPos: SHI[h.seq],
    flipPos: flipMap[h.seq], isTarget: h.key === targetKey,
  }));
}

